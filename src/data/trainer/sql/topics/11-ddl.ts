/*
 * Структура таблиц от данных не зависит, а скрытый набор обязан давать другой ответ.
 * Поэтому ученик заполняет созданные таблицы строками из набора, а проверка добавляет
 * число строк: так результат следует за данными, но имена ограничений и индексов
 * не сравниваются, если условие их не задаёт.
 */
const rowsOf = (table: string) => `(SELECT count(*) FROM ${table}) AS rows_count`

/** Столбцы таблицы в порядке объявления и число строк в ней. */
const columnsCheck = (table: string, extra = '') => `SELECT column_name, data_type, is_nullable, column_default${extra ? `, ${extra}` : ''}, ${rowsOf(table)}
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = '${table}'
ORDER BY ordinal_position`

/** Ограничения таблицы по определению, без имён, и число строк. */
const constraintsCheck = (table: string, kinds = '') => `SELECT contype::text AS kind, pg_get_constraintdef(oid) AS definition, ${rowsOf(table)}
FROM pg_constraint
WHERE conrelid = 'public.${table}'::regclass${kinds ? ` AND contype IN (${kinds})` : ''}
ORDER BY kind, definition`

/** Индексы таблицы по определению без имени индекса и число строк. */
const indexesCheck = (table: string) => `SELECT regexp_replace(indexdef, '^CREATE (UNIQUE )?INDEX \\S+ ON ', 'CREATE \\1INDEX ON ') AS definition, ${rowsOf(table)}
FROM pg_indexes
WHERE schemaname = 'public' AND tablename = '${table}'
ORDER BY definition`

/** Строки таблицы и настройки счётчика столбца id: если условие требует IDENTITY, serial проверку не пройдёт. */
const identityCheck = (table: string, columns: readonly string[], withSteps = false) => `SELECT ${columns.map((column) => `t.${column}`).join(', ')}, c.identity_generation${withSteps ? ', c.identity_start, c.identity_increment' : ''}
FROM ${table} t
CROSS JOIN information_schema.columns c
WHERE c.table_schema = 'public' AND c.table_name = '${table}' AND c.column_name = 'id'
ORDER BY t.id`

