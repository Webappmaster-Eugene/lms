/**
 * Ответ потока урока о состоянии файла на Яндекс Диске.
 *
 * Браузер сообщает плееру только код ошибки и не отличает отказ Диска от обрыва интернета
 * у ученика. Заголовок даёт плееру объяснить ученику, на чьей стороне сбой.
 */
export const MEDIA_SOURCE_HEADER = 'X-Media-Source'

/**
 * unavailable - Диск не отдал файл; missing - файла нет по этому пути;
 * degraded - файл отдаётся, но недавно Диск отказал в его части.
 */
export type MediaSourceStatus = 'unavailable' | 'missing' | 'degraded'
