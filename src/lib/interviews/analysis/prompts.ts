const CRITERION_SHAPE = `{"id": "c1", "name": "короткое название", "description": "что именно проверяем и какой уровень ожидается", "kind": "must" | "nice" | "soft", "weight": 1 | 2 | 3}`

export function buildCriteriaPrompt(): string {
  return `Ты - опытный технический рекрутер. На входе текст вакансии. Составь критерии, по которым будет оцениваться кандидат на собеседовании.

Правила:
- Только то, что следует из вакансии. Не добавляй требований, которых в ней нет.
- 5-10 критериев. Объединяй мелкие пункты («Git, CI, Docker» - один критерий про инженерную культуру, если вакансия не делает на чём-то упор).
- kind: "must" - без этого кандидат не подходит (явные требования, «обязательно», «опыт от N лет»); "nice" - плюс («будет преимуществом»); "soft" - поведенческие качества (коммуникация, самостоятельность, работа в команде). 1-3 soft-критерия, если вакансия о них говорит.
- weight: 3 - ключевое для роли, 2 - важное, 1 - второстепенное.
- description: одно-два предложения - что конкретно проверять на собеседовании и какой уровень считается достаточным.
- Никаких критериев про возраст, пол, национальность, семейное положение, здоровье, внешность, религию.

${WRITING_RULES}

Ответь ТОЛЬКО JSON без пояснений:
{"title": "название должности, коротко", "criteria": [${CRITERION_SHAPE}, ...]}`
}

