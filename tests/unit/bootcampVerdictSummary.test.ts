import { describe, expect, it } from 'vitest'

import { verdictSummary } from '@/server/bootcamp-gitlab-events'

const report = (headline: string, count = 'Коммит `5d1444952459`, попытка 1. Прошло проверок: 26 из 26.') => [
  '<!-- grader:01:5d144495245925e03934d5445e6f059c9b19c79d -->',
  `**Доверенная проверка: ${headline}**`,
  '',
  count,
  '',
  '| Проверка | Итог | Прошло | Задание |',
  '|---|---|---|---|',
  '| основная | пройдена | 26 из 26 | [журнал](https://git.test/jobs/1) |',
].join('\n')

describe('итог проверки для журнала и Telegram', () => {
  it('берёт неделю, вердикт и счёт, а служебную метку и таблицу отбрасывает', () => {
    expect(verdictSummary(report('неделя 1 — пройдена'))).toBe('неделя 1 - пройдена, прошло 26 из 26')
  })

  it('длинные тире заменяет во всём заголовке', () => {
    expect(verdictSummary(report('неделя 8 — не выполнена целиком — не зачтено'))).toBe('неделя 8 - не выполнена целиком - не зачтено, прошло 26 из 26')
  })

  it('обходится без счёта, если его нет', () => {
    expect(verdictSummary(report('входное задание — пройдена', 'Коммит `abc`.'))).toBe('входное задание - пройдена')
  })

  it('незнакомый текст бота показывает как есть, но без служебной метки', () => {
    expect(verdictSummary('<!-- метка -->\nПроверка отложена')).toBe('Проверка отложена')
  })
})
