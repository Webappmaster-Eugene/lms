const CAREER_START = new Date('2021-08-01')

function yearsSince(start: Date): string {
  const now = new Date()
  const years = now.getFullYear() - start.getFullYear() - (now.getMonth() < start.getMonth() ? 1 : 0)
  const last = years % 10
  const noun = years % 100 >= 11 && years % 100 <= 14 ? 'лет' : last === 1 ? 'год' : last >= 2 && last <= 4 ? 'года' : 'лет'
  return `${years} ${noun}`
}

